/**
 * The supervisor: a tiny plain-JS program that the OS scheduler executes
 * for each tick of a job. It wraps `opencode run` with:
 *
 * - no-overlap locking (a live run blocks the next tick)
 * - job metadata updates (running/success/failed, exit code)
 * - append-only run history (runs/<slug>.jsonl)
 * - an optional hard timeout (SIGTERM to the process group, then SIGKILL)
 * - a clean environment (OPENCODE_* vars from the invoking session are
 *   scrubbed so scheduled runs do not inherit interactive state)
 *
 * It runs outside the opencode server (spawned by systemd, cron, or the
 * run_job tool), so it must be plain CommonJS with no dependencies and no
 * imports from this plugin. The absolute path of a node (or bun) binary is
 * recorded in the scheduler unit when the job is installed.
 */
import { existsSync, readFileSync, writeFileSync } from "fs"
import { SCHEDULER_DIR, SUPERVISOR_PATH, ensureDir } from "./config.js"

export const SUPERVISOR_VERSION = 2

// Written as a plain string: no template literals or interpolation inside,
// so it stays readable and never accidentally captures plugin state.
const SUPERVISOR_SCRIPT = [
  "#!/usr/bin/env node",
  "// opencode-scheduler supervisor v" + SUPERVISOR_VERSION,
  "// usage: supervisor.js <job.json> [--source manual|scheduled]",
  '"use strict"',
  "",
  "var fs = require('fs')",
  "var path = require('path')",
  "var childProcess = require('child_process')",
  "",
  "function fail(message) {",
  "  try { process.stderr.write('supervisor: ' + message + '\\n') } catch (e) {}",
  "  process.exit(1)",
  "}",
  "",
  "function isoNow() {",
  "  return new Date().toISOString()",
  "}",
  "",
  "function readJson(file) {",
  "  return JSON.parse(fs.readFileSync(file, 'utf8'))",
  "}",
  "",
  "function writeJsonAtomic(file, data) {",
  "  var tmp = file + '.tmp.' + process.pid",
  "  fs.writeFileSync(tmp, JSON.stringify(data, null, 2) + '\\n')",
  "  fs.renameSync(tmp, file)",
  "}",
  "",
  "function appendJsonl(file, data) {",
  "  fs.appendFileSync(file, JSON.stringify(data) + '\\n')",
  "}",
  "",
  "function pidAlive(pid) {",
  "  if (!pid || pid <= 0) return false",
  "  try { process.kill(pid, 0); return true }",
  "  catch (err) { return err.code === 'EPERM' }",
  "}",
  "",
  "var jobPath = process.argv[2]",
  "if (!jobPath) fail('usage: supervisor.js <job.json> [--source manual|scheduled]')",
  "",
  "var sourceIndex = process.argv.indexOf('--source')",
  "var source = sourceIndex !== -1 && process.argv[sourceIndex + 1] === 'manual' ? 'manual' : 'scheduled'",
  "",
  "var job = readJson(jobPath)",
  "var scopeId = job.scopeId",
  "var slug = job.slug",
  "if (!scopeId || !slug) fail('job missing scopeId/slug')",
  "",
  "var home = process.env.HOME",
  "if (!home) fail('HOME is not set')",
  "",
  "var configRoot = path.join(home, '.config', 'opencode')",
  "var scopeRoot = path.join(configRoot, 'scheduler', 'scopes', scopeId)",
  "var locksDir = path.join(scopeRoot, 'locks')",
  "var runsDir = path.join(scopeRoot, 'runs')",
  "var logsDir = path.join(configRoot, 'logs', 'scheduler', scopeId)",
  "for (var d of [locksDir, runsDir, logsDir]) {",
  "  try { fs.mkdirSync(d, { recursive: true }) } catch (e) {}",
  "}",
  "",
  "var logPath = path.join(logsDir, slug + '.log')",
  "var logStream = fs.createWriteStream(logPath, { flags: 'a' })",
  "function log(text) {",
  "  try { logStream.write(text) } catch (e) {}",
  "}",
  "function finish(exitCode) {",
  "  // Flush pending stream writes before exiting, or the log tail is lost.",
  "  try {",
  "    logStream.end(function () { process.exit(exitCode) })",
  "    setTimeout(function () { process.exit(exitCode) }, 2000).unref()",
  "  } catch (e) { process.exit(exitCode) }",
  "}",
  "",
  "var lockPath = path.join(locksDir, slug + '.json')",
  "try {",
  "  var existing = readJson(lockPath)",
  "  if (pidAlive(existing && existing.pid)) {",
  "    log('\\n=== ' + isoNow() + ' run skipped (' + source + '): already running pid=' + existing.pid + ' runId=' + existing.runId + ' ===\\n')",
  "    finish(0)",
  "    return",
  "  }",
  "  // Stale lock from a crashed run: take over.",
  "  fs.unlinkSync(lockPath)",
  "} catch (e) {",
  "  // No lock or unreadable lock: proceed.",
  "}",
  "",
  "var startedAt = isoNow()",
  "var t0 = Date.now()",
  "var runId = String(t0) + '-' + String(Math.floor(Math.random() * 1e9))",
  "",
  "writeJsonAtomic(lockPath, { pid: process.pid, startedAt: startedAt, runId: runId, source: source })",
  "",
  "function updateJob(fields) {",
  "  try {",
  "    var current = readJson(jobPath)",
  "    for (var key in fields) {",
  "      if (fields[key] === undefined) delete current[key]",
  "      else current[key] = fields[key]",
  "    }",
  "    current.updatedAt = isoNow()",
  "    writeJsonAtomic(jobPath, current)",
  "  } catch (e) {",
  "    log('\\n=== supervisor warning: could not update job metadata: ' + e.message + ' ===\\n')",
  "  }",
  "}",
  "",
  "var invocation = job.invocation",
  "if (!invocation || !invocation.command || !Array.isArray(invocation.args)) {",
  "  log('\\n=== ' + isoNow() + ' supervisor error: job has no invocation snapshot ===\\n')",
  "  updateJob({ lastRunStatus: 'failed', lastRunError: 'job missing invocation' })",
  "  try { fs.unlinkSync(lockPath) } catch (e) {}",
  "  finish(1)",
  "  return",
  "}",
  "",
  "updateJob({",
  "  lastRunAt: startedAt,",
  "  lastRunSource: source,",
  "  lastRunStatus: 'running',",
  "  lastRunExitCode: undefined,",
  "  lastRunError: undefined,",
  "})",
  "",
  "// Clean environment: drop OPENCODE_* vars from the invoking session so",
  "// scheduled runs do not inherit interactive state, keep OPENCODE_SCHEDULER_*",
  "// overrides, then apply the scheduler config env.set if present.",
  "var env = {}",
  "for (var name in process.env) {",
  "  if (name.indexOf('OPENCODE_') === 0 && name.indexOf('OPENCODE_SCHEDULER_') !== 0) continue",
  "  env[name] = process.env[name]",
  "}",
  "var baseEntries = ['/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin']",
  "var extraDirs = [",
  "  invocation.command && path.dirname(invocation.command),",
  "  process.execPath && path.dirname(process.execPath),",
  "].filter(Boolean)",
  "for (var dir of extraDirs) { if (baseEntries.indexOf(dir) === -1) baseEntries.unshift(dir) }",
  "env.PATH = (env.PATH ? env.PATH.split(':') : []).concat(baseEntries).filter(function (value, index, list) {",
  "  return list.indexOf(value) === index",
  "}).join(':')",
  "try {",
  "  var schedulerConfig = readJson(path.join(configRoot, 'opencode-scheduler.json'))",
  "  if (schedulerConfig && schedulerConfig.env && schedulerConfig.env.set) {",
  "    for (var key in schedulerConfig.env.set) env[key] = schedulerConfig.env.set[key]",
  "  }",
  "} catch (e) {}",
  "",
  "log('\\n=== ' + startedAt + ' ' + source + ' run start runId=' + runId + ' ===\\n')",
  "",
  "var workdir = job.workdir || home",
  "var timeoutSeconds = typeof job.timeoutSeconds === 'number' && job.timeoutSeconds > 0 ? job.timeoutSeconds : 0",
  "var timedOut = false",
  "var killTimer = null",
  "var child = null",
  "",
  "try {",
  "  child = childProcess.spawn(invocation.command, invocation.args, {",
  "    cwd: workdir,",
  "    env: env,",
  "    detached: true,",
  "    stdio: ['ignore', 'pipe', 'pipe'],",
  "  })",
  "} catch (err) {",
  "  failAtSpawn(err)",
  "  return",
  "}",
  "",
  "if (child.stdout) child.stdout.pipe(logStream, { end: false })",
  "if (child.stderr) child.stderr.pipe(logStream, { end: false })",
  "",
  "function killGroup(signal) {",
  "  if (!child || !child.pid) return",
  "  try { process.kill(-child.pid, signal) } catch (e) {",
  "    try { child.kill(signal) } catch (e2) {}",
  "  }",
  "}",
  "",
  "if (timeoutSeconds > 0) {",
  "  killTimer = setTimeout(function () {",
  "    timedOut = true",
  "    log('\\n=== ' + isoNow() + ' timeout after ' + timeoutSeconds + 's: sending SIGTERM ===\\n')",
  "    killGroup('SIGTERM')",
  "    setTimeout(function () {",
  "      log('\\n=== ' + isoNow() + ' escalation: sending SIGKILL ===\\n')",
  "      killGroup('SIGKILL')",
  "    }, 10000).unref()",
  "  }, timeoutSeconds * 1000)",
  "  killTimer.unref()",
  "}",
  "",
  "function failAtSpawn(err) {",
  "  log('\\n=== ' + isoNow() + ' supervisor error: spawn failed: ' + err.message + ' ===\\n')",
  "  updateJob({ lastRunStatus: 'failed', lastRunError: 'spawn failed: ' + err.message })",
  "  try { fs.unlinkSync(lockPath) } catch (e) {}",
  "  finish(1)",
  "}",
  "",
  "child.on('error', function (err) { failAtSpawn(err) })",
  "",
  "child.on('close', function (code, signal) {",
  "  if (killTimer) clearTimeout(killTimer)",
  "  var finishedAt = isoNow()",
  "  var durationMs = Date.now() - t0",
  "  var exitCode = timedOut ? 124 : (typeof code === 'number' ? code : 1)",
  "  var status = exitCode === 0 ? 'success' : 'failed'",
  "  var error = timedOut ? 'timeout after ' + timeoutSeconds + 's' : (signal ? 'killed by ' + signal : (exitCode === 0 ? undefined : 'exit code ' + exitCode))",
  "",
  "  updateJob({",
  "    lastRunStatus: status,",
  "    lastRunExitCode: exitCode,",
  "    lastRunError: error,",
  "  })",
  "",
  "  try {",
  "    appendJsonl(path.join(runsDir, slug + '.jsonl'), {",
  "      runId: runId,",
  "      scopeId: scopeId,",
  "      slug: slug,",
  "      source: source,",
  "      startedAt: startedAt,",
  "      finishedAt: finishedAt,",
  "      durationMs: durationMs,",
  "      status: status,",
  "      exitCode: exitCode,",
  "      error: error,",
  "      pid: child.pid,",
  "      logPath: logPath,",
  "    })",
  "  } catch (e) {}",
  "",
  "  try { fs.unlinkSync(lockPath) } catch (e) {}",
  "  log('\\n=== ' + finishedAt + ' run ' + status + ' exitCode=' + exitCode + ' durationMs=' + durationMs + ' ===\\n')",
  "  finish(exitCode)",
  "})",
  "",
].join("\n")

let supervisorCache: string | null = null

function supervisorSource(): string {
  if (supervisorCache === null) {
    supervisorCache = SUPERVISOR_SCRIPT + "\n"
  }
  return supervisorCache
}

/**
 * Write the supervisor script if it is missing or outdated. Rewriting is
 * safe: the script is read once at process start, so an in-flight run keeps
 * its own copy in memory.
 */
export function ensureSupervisorScript(): string {
  ensureDir(SCHEDULER_DIR)
  if (!existsSync(SUPERVISOR_PATH) || readFileSync(SUPERVISOR_PATH, "utf-8") !== supervisorSource()) {
    writeFileSync(SUPERVISOR_PATH, supervisorSource())
  }
  return SUPERVISOR_PATH
}
